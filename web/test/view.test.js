import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import test from "node:test";
import { escapeHtml, renderApp } from "../view.js";

const base = {
  route: "dashboard", signedIn: true, mutationReady: true, busy: false, error: null, notice: null,
  overview: { accounts: [], connections: {}, capabilities: {}, audit: [], health: { ready: true, checks: {} } },
  keys: null, keysUnavailable: false, backups: null, upgrade: null, settingsUnavailable: false, action: null,
};

test("dashboard has navigation, health, empty states, and accessible landmarks", () => {
  const html = renderApp(base);
  assert.match(html, /aria-label="Primary"/);
  assert.match(html, /System operational/);
  assert.match(html, /Add your first account/);
  assert.match(html, /<main id="main"/);
});

test("account and audit values are escaped before rendering", () => {
  const html = renderApp({ ...base, overview: { ...base.overview, accounts: [{ id: "a1", platform: "reddit", expectedNativeUserId: "<img src=x>", actualNativeUserId: null, label: "<script>alert(1)</script>", status: "active", createdAt: "2026-01-01T00:00:00Z", updatedAt: "2026-01-01T00:00:00Z" }], connections: { a1: null } } });
  assert.doesNotMatch(html, /<script>alert/);
  assert.match(html, /&lt;script&gt;alert\(1\)&lt;\/script&gt;/);
  assert.equal(escapeHtml('a&<"'), "a&amp;&lt;&quot;");
});

test("missing DYN-106 APIs render honest actionable states rather than fake records", () => {
  const keys = renderApp({ ...base, route: "keys", keysUnavailable: true });
  const settings = renderApp({ ...base, route: "settings", settingsUnavailable: true });
  assert.match(keys, /API key service/);
  assert.match(keys, /Inspect available endpoints/);
  assert.match(settings, /owner operations service/);
  assert.doesNotMatch(keys, /Production automation/);
});

test("settings render only generated backup metadata and keep upgrades explicitly manual", () => {
  const html = renderApp({
    ...base,
    route: "settings",
    backups: { items: [{
      id: "backup-20260917T120000Z-aabbccddeeff",
      status: "ready",
      createdAt: "2026-09-17T12:00:00Z",
      expiresAt: "2026-10-17T12:00:00Z",
      completedAt: "2026-09-17T12:00:01Z",
      sizeBytes: 4096,
      databaseCount: 3,
    }] },
    upgrade: { currentVersion: "0.1.0", latestVersion: null, updateAvailable: false, channel: "manual", automation: "unavailable", message: "Remote update checks and automatic upgrades are disabled." },
  });
  assert.match(html, /Encrypted recovery sets/);
  assert.match(html, /backup-20260917T120000Z-aabbccddeeff/);
  assert.match(html, /4\.0 KiB/u);
  assert.match(html, /3 databases/u);
  assert.match(html, /Paths and filenames are generated by Core/u);
  assert.match(html, /Automatic upgrades and remote update checks are unavailable/u);
  assert.doesNotMatch(html, /href="https:\/\/github\.com\/"/u);
});

test("API key form exposes every supported least-privilege scope", () => {
  const html = renderApp({ ...base, route: "keys" });
  for (const scope of [
    "accounts:write", "accounts:read", "connections:write", "connections:read",
    "social:read", "social:write", "actions:read", "audit:read",
    "webhooks:read", "webhooks:write",
  ]) {
    assert.match(html, new RegExp(`value="${scope}"`, "u"));
  }
});

